def section_system_prompt(
    section: str,
    template: str = "equity_deep",
    depth_spec: str = "",
) -> str:
    """报告单段撰写 system prompt：IDENTITY + COMPLIANCE + 模板侧重 + 段任务 + 格式 + 篇幅。

    模板侧重必须进来：否则 risk/industry/earnings 模板下的技术面段与 equity_deep
    逐字相同，模板差异只剩摘要一段。

    depth_spec 来自 llm.reasoning_profile()，是用户选的思考档位对应的篇幅深度指令。
    """
    t = (template or "equity_deep").strip()
    focus = TEMPLATE_FOCUS.get(t, TEMPLATE_FOCUS["equity_deep"])
    task = SECTION_TASK.get(section, "")
    parts = [IDENTITY, COMPLIANCE, focus, task, REPORT_OUTPUT_SPEC]
    if depth_spec:
        parts.append(depth_spec)
    return "\n".join(p for p in parts if p)


def report_system_prompt(
    titles: list[str],
    template: str = "equity_deep",
    depth_spec: str = "",
) -> str:
    """整篇报告一次撰写的 system prompt。

    与 section_system_prompt 的关键差别：把各段写作任务按顺序合并成一份提纲，
    并明确列出必须出现的段标题——整篇流式靠识别【段标题】行来切段，
    标题写错或漏写会导致该段被判为缺失、退回规则模板。

    段任务用【部分N】编号列出而不是简单拼接：模型看到编号会更严格地按序输出，
    实测比"请依次撰写以下部分"这种叙述式指令稳定。
    """
    t = (template or "equity_deep").strip()
    focus = TEMPLATE_FOCUS.get(t, TEMPLATE_FOCUS["equity_deep"])
    # 摘要并入整篇流的首个分段
    full_titles = [("summary", "投资摘要")] + list(titles)
    outline = "\n".join(
        f"【部分{i}】标题必须写作「{title}」\n{SECTION_TASK.get(key, '')}"
        for i, (key, title) in enumerate(full_titles, start=1)
    )
    order = "、".join(title for _key, title in titles)
    task = (
        "【整篇撰写任务】一次性写完下列全部部分，按给定顺序连续输出，中途不要停顿、"
        "不要询问、不要输出任何与报告正文无关的说明文字。\n"
        f"必须依次出现且仅出现这些部分：{order}。\n"
        f"{outline}"
    )
    parts = [IDENTITY, COMPLIANCE, focus, task, REPORT_OUTPUT_SPEC]
    if depth_spec:
        parts.append(depth_spec)
    return "\n".join(p for p in parts if p)
