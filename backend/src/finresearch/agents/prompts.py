def research_system_prompt(template: str) -> str:
    """研究链路 system prompt 基线：IDENTITY + COMPLIANCE + 模板侧重。

    画像/时间/事实块由 context 层在其后追加（段序固定）。
    """
    t = (template or "equity_deep").strip()
    focus = TEMPLATE_FOCUS.get(t, TEMPLATE_FOCUS["equity_deep"])
    return f"{IDENTITY}\n{COMPLIANCE}\n{focus}"


def summary_system_prompt(template: str) -> str:
    """投资摘要 system prompt：IDENTITY + COMPLIANCE + 摘要写作标准 + 模板侧重。

    替代原 report.py 用 research_prompt（弱 _BASE）的旧路径，真正接上高质量摘要提示词。
    """
    t = (template or "equity_deep").strip()
    focus = TEMPLATE_FOCUS.get(t, TEMPLATE_FOCUS["equity_deep"])
    return f"{IDENTITY}\n{COMPLIANCE}\n{SUMMARY_WRITING_STANDARD}\n{focus}"


def section_system_prompt(section: str, template: str = "equity_deep") -> str:
    """报告单段撰写 system prompt：IDENTITY + COMPLIANCE + 模板侧重 + 段写作任务。

    模板侧重必须进来：否则 risk/industry/earnings 模板下的技术面段与 equity_deep
    逐字相同，模板差异只剩摘要一段。
    """
    t = (template or "equity_deep").strip()
    focus = TEMPLATE_FOCUS.get(t, TEMPLATE_FOCUS["equity_deep"])
    task = SECTION_TASK.get(section, "")
    return f"{IDENTITY}\n{COMPLIANCE}\n{focus}\n{task}"
